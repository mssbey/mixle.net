import puppeteer from 'puppeteer-core';
import { findChrome } from './chrome-path.mjs';
import { mkdir, writeFile } from 'node:fs/promises';
const browser = await puppeteer.launch({executablePath:findChrome(),headless:true});
const page = await browser.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await mkdir('artifacts/home-reference',{recursive:true});
const results=[];
for (const width of [1920,390]) {
 await page.setViewport({width,height:1000});
 await page.goto('http://localhost:3000',{waitUntil:'networkidle0'});
 await page.evaluate(async()=>{for(const img of document.images){img.loading='eager';}await Promise.all([...document.images].map(i=>i.decode().catch(()=>{})));});
 await page.screenshot({path:`artifacts/home-reference/home-${width}.png`,fullPage:true});
 results.push(await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,height:document.documentElement.scrollHeight,cards:document.querySelectorAll('.product-card').length,broken:[...document.images].filter(i=>!i.naturalWidth).map(i=>i.src)})));
}
await page.setViewport({width:1920,height:1000});
await page.reload({waitUntil:'networkidle0'});
const before=await page.$eval('.reference-hero-frame img',i=>i.getAttribute('alt'));
await page.click('button[aria-label="Sonraki banner"]');
const after=await page.$eval('.reference-hero-frame img',i=>i.getAttribute('alt'));
await page.click('.reference-products button[aria-label="Sonraki"]');
await new Promise(r=>setTimeout(r,500));
const carousel=await page.$eval('.reference-rail-dots button[aria-pressed="true"]',b=>b.getAttribute('aria-label'));
await page.click('.reference-products button[aria-label="\u00d6nceki"]');
await new Promise(r=>setTimeout(r,500));
await page.click('.product-card button.w-full');
await page.waitForSelector('.product-card .absolute.inset-1');
const panel=!!(await page.$('.product-card .absolute.inset-1'));
await new Promise(r=>setTimeout(r,400));
await page.$eval('.product-card',el=>window.scrollTo(0,el.getBoundingClientRect().top+window.scrollY-260));
await new Promise(r=>setTimeout(r,500));
await page.click('.product-card .absolute.inset-1 button.btn-primary');
await page.screenshot({path:'artifacts/home-reference/cart-debug.png'});
await page.waitForSelector('[role=dialog]',{timeout:6000});
await new Promise(r=>setTimeout(r,600));
const cart=await page.$eval('[role=dialog]',el=>el.innerText.includes('Frozen Orchard'));
await page.keyboard.press('Escape');
await page.waitForSelector('[role=dialog]',{hidden:true});
await page.click('.reference-subscriptions button[type=submit]');
await page.waitForSelector('.reference-subscriptions input[aria-invalid="true"]',{timeout:5000});
const validation=await page.$eval('.reference-subscriptions input',el=>el.getAttribute('aria-invalid')==='true');
await writeFile('artifacts/home-reference/report.json',JSON.stringify({results,errors,heroChanges:before!==after,carousel,panel,cart,validation},null,2));
console.log(JSON.stringify({results,errors,heroChanges:before!==after,carousel,panel,cart,validation},null,2));
await browser.close();
